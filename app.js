// Глобальное делегирование кликов
document.addEventListener('click', function(ev) {
    const t = ev.target;

    // Показать/скрыть пароль
    const passBtn = t.closest('.toggle-pass-btn');
    if (passBtn) {
        const input = $(passBtn.dataset.target);
        if (input) {
            input.type = input.type === 'password' ? 'text' : 'password';
            passBtn.textContent = input.type === 'password' ? '👁️' : '🙈';
        }
        return;
    }

    // Вкладки внутри окна авторизации (Регистрация / Вход / Сброс)
    if (t.dataset.authTab) {
        document.querySelectorAll('[data-auth-tab]').forEach(function(b) { b.classList.toggle('active', b === t); });
        $('register-form').hidden = t.dataset.authTab !== 'register';
        $('login-form').hidden = t.dataset.authTab !== 'login';
        $('recover-form').hidden = t.dataset.authTab !== 'recover';
        showAccountMessage('', '');
        return;
    }

    // Вкладки внутри авторизованного профиля
    if (t.dataset.profileTab) {
        document.querySelectorAll('[data-profile-tab]').forEach(function(b) { b.classList.toggle('active', b === t); });
        $('profile-edit-form').hidden = t.dataset.profileTab !== 'edit-profile';
        $('change-password-form').hidden = t.dataset.profileTab !== 'change-password';
        showAccountMessage('', '');
        return;
    }

    // Добавление/удаление упражнения из «Моих»
    if (t.dataset.toggle) {
        ev.stopPropagation();
        const id = Number(t.dataset.toggle);
        myIds = myIds.includes(id) ? myIds.filter(function(x) { return x !== id; }) : myIds.concat(id);
        save();
        recalculateMetabolismAndWorkout(false);
        renderAll();
        return;
    }

    // Включение/выключение тренажёра прямо из карточки тренажёра
    if (t.dataset.machineToggle) {
        ev.stopPropagation();
        const mId = Number(t.dataset.machineToggle);
        const cb = document.querySelector('.mc-checkbox[value="' + mId + '"]');
        if (cb) {
            cb.checked = !cb.checked;
            if ($('place').value !== 'gym') {
                $('place').value = 'gym';
                applyPlace();
            }
            if ($('auto-sync-program') && $('auto-sync-program').checked) {
                const matched = exercisesDB.filter(isExerciseAvailable);
                if (matched.length > 0) myIds = matched.map(function(e) { return e.id; });
            }
            saveExtra();
            save();
            recalculateMetabolismAndWorkout(false);
            renderAll();
            showToast(cb.checked ? 'Тренажёр включён в расчёт упражнений' : 'Тренажёр исключён из расчёта');
        }
        return;
    }

    // Лайк тренажёра (влияет на приоритет в расчёте)
    if (t.dataset.like) {
        ev.stopPropagation();
        const id = Number(t.dataset.like);
        likedMachines = likedMachines.includes(id)
            ? likedMachines.filter(function(x) { return x !== id; })
            : likedMachines.concat(id);
        save();
        recalculateMetabolismAndWorkout(false);
        renderAll();
        return;
    }

    // Закрытие модальных окон по клику на фон или кнопку закрытия
    if (t.id === 'modal' || t.dataset.close) { $('modal').hidden = true; return; }
    if (t.id === 'account-modal') { $('account-modal').hidden = true; return; }
    if (t.id === 'confirm-modal' || t.id === 'close-confirm-modal' || t.id === 'cancel-delete-btn') {
        $('confirm-modal').hidden = true;
        return;
    }

    // Переключение основных вкладок
    const tabBtn = t.closest('.tab[data-tab]');
    if (tabBtn) {
        document.querySelectorAll('.tab').forEach(function(b) { b.classList.toggle('active', b === tabBtn); });
        document.querySelectorAll('.tab-panel').forEach(function(p) { p.hidden = (p.id !== 'tab-' + tabBtn.dataset.tab); });
        return;
    }

    // Клик по карточке упражнения — открытие инструкции и расчёта
    const card = t.closest('.exercise-card[data-id]');
    if (card) openModal(Number(card.dataset.id));
});

