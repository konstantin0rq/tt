function renderAll() {
    const val = function(id) { return $(id) ? $(id).value.trim().toLowerCase() : ''; };
    const hideUnavailable = $('filter-by-available') ? $('filter-by-available').checked : false;

    const myList = exercisesDB.filter(function(e) {
        if (!myIds.includes(e.id)) return false;
        if (hideUnavailable && !isExerciseAvailable(e)) return false;
        const q = val('search-my');
        if (!q) return true;
        return e.name.toLowerCase().includes(q) || e.tags.some(function(t) { return t.toLowerCase().includes(q); });
    });

    // Сортируем «Мои упражнения»: сначала доступные и на любимых тренажёрах
    myList.sort(function(a, b) {
        const avA = isExerciseAvailable(a) ? 1 : 0;
        const avB = isExerciseAvailable(b) ? 1 : 0;
        if (avA !== avB) return avB - avA;
        const favA = a.machineId && likedMachines.includes(a.machineId) ? 1 : 0;
        const favB = b.machineId && likedMachines.includes(b.machineId) ? 1 : 0;
        return favB - favA;
    });

    $('exercises-grid').innerHTML = myList.length
        ? myList.map(exCard).join('')
        : '<p class="placeholder-text">Упражнений по текущему выбору тренажёров/инвентаря не найдено. Нажмите кнопку «Подобрать упражнения под мои тренажёры» выше или выберите больше инвентаря слева.</p>';

    const fm = $('f-muscle').value;
    const fe = $('f-eq').value;
    const fmac = $('f-machine') ? $('f-machine').value : '';
    const fl = $('f-level').value;
    const qAll = val('search-all');

    const allFiltered = exercisesDB.filter(function(e) {
        const matchQuery = !qAll || e.name.toLowerCase().includes(qAll) || e.tags.some(function(t) { return t.toLowerCase().includes(qAll); });
        const matchM = !fm || e.muscle === fm;
        const matchE = !fe || e.equipment === fe;
        const matchMac = !fmac || String(e.machineId || '') === fmac;
        const matchL = !fl || e.level === fl;
        return matchQuery && matchM && matchE && matchMac && matchL;
    });

    $('all-grid').innerHTML = allFiltered.length
        ? allFiltered.map(exCard).join('')
        : '<p class="placeholder-text">Ничего не найдено по заданным фильтрам.</p>';

    // Понравившиеся тренажёры показываются первыми
    const sorted = machinesDB.slice().sort(function(a, b) {
        return Number(likedMachines.includes(b.id)) - Number(likedMachines.includes(a.id));
    });
    $('machines-grid').innerHTML = sorted.map(machineCard).join('');

    const liked = sorted.filter(function(m) { return likedMachines.includes(m.id); });
    $('liked-grid').innerHTML = liked.length
        ? liked.map(machineCard).join('')
        : '<p class="placeholder-text">Нажмите сердечко 🤍 на любом тренажёре, чтобы добавить его в любимые и дать ему приоритет при расчёте программы.</p>';

    // Обновляем счётчики на вкладках
    if ($('tab-btn-my')) $('tab-btn-my').dataset.count = myList.length;
    if ($('tab-btn-all')) $('tab-btn-all').dataset.count = allFiltered.length;
    if ($('tab-btn-machines')) $('tab-btn-machines').dataset.count = machinesDB.length;
    if ($('tab-btn-liked')) $('tab-btn-liked').dataset.count = liked.length;
}

