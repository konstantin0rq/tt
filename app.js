// Сжатие загруженного пользователем изображения через Canvas до аккуратного квадрата 160x160
function handleAvatarFileUpload(fileInput, callback) {
    fileInput.addEventListener('change', function() {
        const file = fileInput.files && fileInput.files[0];
        if (!file) return;
        if (!file.type.startsWith('image/')) {
            showAccountMessage('Пожалуйста, выберите файл изображения (PNG, JPG, WEBP).', 'error');
            return;
        }
        const reader = new FileReader();
        reader.onload = function(e) {
            const img = new Image();
            img.onload = function() {
                const canvas = document.createElement('canvas');
                const size = 160;
                canvas.width = size;
                canvas.height = size;
                const ctx = canvas.getContext('2d');
                const minSide = Math.min(img.width, img.height);
                const sx = (img.width - minSide) / 2;
                const sy = (img.height - minSide) / 2;
                ctx.drawImage(img, sx, sy, minSide, minSide, 0, 0, size, size);
                const dataUrl = canvas.toDataURL('image/jpeg', 0.85);
                callback(dataUrl);
            };
            img.src = e.target.result;
        };
        reader.readAsDataURL(file);
    });
}

// Оценка надёжности пароля
function evaluatePasswordStrength(pass) {
    if (!pass) return { pct: 0, color: '#444', label: 'Введите пароль' };
    let score = 0;
    if (pass.length >= 6) score += 25;
    if (pass.length >= 9) score += 25;
    if (/[A-ZА-Я]/.test(pass) && /[a-zа-я]/.test(pass)) score += 25;
    if (/[0-9]/.test(pass) || /[^A-Za-zА-Яа-я0-9]/.test(pass)) score += 25;

    if (score <= 25) return { pct: 30, color: '#ff5252', label: 'Слабый пароль' };
    if (score <= 50) return { pct: 60, color: '#ffa726', label: 'Средний пароль' };
    return { pct: 100, color: '#00e676', label: 'Надёжный пароль' };
}

function wirePasswordLiveChecks(passId, repeatId, fillId, strengthTextId, matchTextId) {
    const passEl = $(passId);
    const repEl = $(repeatId);
    const fillEl = $(fillId);
    const strText = $(strengthTextId);
    const matchText = $(matchTextId);

    function update() {
        const val = passEl.value;
        const rep = repEl.value;
        const st = evaluatePasswordStrength(val);
        if (fillEl) {
            fillEl.style.width = st.pct + '%';
            fillEl.style.backgroundColor = st.color;
        }
        if (strText) {
            strText.textContent = st.label;
            strText.style.color = st.color;
        }
        if (matchText) {
            if (!rep) {
                matchText.textContent = 'Повторите пароль';
                matchText.className = 'field-hint';
            } else if (val === rep) {
                matchText.textContent = '✓ Пароли совпадают';
                matchText.className = 'field-hint match-ok';
            } else {
                matchText.textContent = '✕ Пароли не совпадают';
                matchText.className = 'field-hint match-err';
            }
        }
    }

    passEl.addEventListener('input', update);
    repEl.addEventListener('input', update);
}

