function recalculateMetabolismAndWorkout(showValidationErrors) {
    const selectedEquipment = selectedEquipmentList();
    const selectedMuscles = selectedMusclesList();
    const activeMachines = availMachines();
    const place = $('place').value;
    const goal = $('goal').value;

    const userData = {
        gender: $('gender').value || 'male',
        age: Number($('age').value) || 25,
        weight: Number($('weight').value) || 75,
        targetWeight: Number($('target-weight').value) || 75,
        targetDays: Number($('target-days').value) || 90,
        height: Number($('height').value) || 178,
        activity: Number($('activity').value) || 1.55,
        equipment: selectedEquipment,
        muscleGroup: selectedMuscles
    };

    if (showValidationErrors) {
        if (goal === 'gain' && userData.targetWeight < userData.weight) {
            adviceBox.style.display = 'block';
            adviceBox.style.borderLeftColor = '#ff5252';
            adviceBox.innerHTML = '<strong style="color: #ff5252;">⚠️ Ошибка логики!</strong> Вы выбрали «Набор массы», но желаемый вес меньше текущего.';
            return false;
        }
        if (goal === 'loss' && userData.targetWeight > userData.weight) {
            adviceBox.style.display = 'block';
            adviceBox.style.borderLeftColor = '#ff5252';
            adviceBox.innerHTML = '<strong style="color: #ff5252;">⚠️ Ошибка логики!</strong> Вы выбрали «Сброс веса», но желаемый вес больше текущего.';
            return false;
        }
        if (userData.targetWeight !== userData.weight && userData.targetDays < 14) {
            adviceBox.style.display = 'block';
            adviceBox.style.borderLeftColor = '#ff5252';
            adviceBox.innerHTML = '<strong style="color: #ff5252;">⚠️ Слишком быстро!</strong> Изменить вес менее чем за 14 дней невозможно без вреда для здоровья. Увеличьте срок.';
            return false;
        }
        if (place === 'home' && selectedEquipment.length === 0) {
            adviceBox.style.display = 'block';
            adviceBox.style.borderLeftColor = '#ffa726';
            adviceBox.innerHTML = '<strong style="color: #ffa726;">⚠️ Инвентарь не выбран!</strong> Пожалуйста, поставьте хотя бы одну галочку в разделе доступного инвентаря.';
            return false;
        }
        if (place === 'gym' && activeMachines.length === 0) {
            adviceBox.style.display = 'block';
            adviceBox.style.borderLeftColor = '#ffa726';
            adviceBox.innerHTML = '<strong style="color: #ffa726;">⚠️ Тренажёры не выбраны!</strong> Отметьте хотя бы один тренажёр в вашем зале для расчёта тренировки.';
            return false;
        }
    }

    adviceBox.style.borderLeftColor = '#00e676';

    // 1. Расчёт BMR (Миффлин - Сан Жеор)
    let bmr = (10 * userData.weight) + (6.25 * userData.height) - (5 * userData.age);
    bmr += (userData.gender === 'male') ? 5 : -161;
    bmr = Math.round(bmr);

    // 2. Расчёт энергозатрат выбранного комплекса упражнений и тренажёров
    const activeMyExercises = exercisesDB.filter(function(ex) {
        return myIds.includes(ex.id) && isExerciseAvailable(ex);
    });
    const sampleWorkout = activeMyExercises.slice(0, 8);
    let workoutBurn = 0;
    sampleWorkout.forEach(function(ex) {
        workoutBurn += calculateExercisePrescription(ex).kcal;
    });
    // Бонус от количества тяжёлых базовых тренажёров в зале
    if (place === 'gym') {
        const heavyCount = activeMachines.filter(function(id) { return [1, 5, 6, 7, 10, 13, 16, 18].includes(id); }).length;
        workoutBurn += heavyCount * 12;
    }
    workoutBurn = Math.max(140, Math.round(workoutBurn * (userData.weight / 75)));
    const estDurationMin = Math.max(25, sampleWorkout.length * 7 + 10);

    // 3. Суточная норма калорий с учётом интенсивности выбранных тренажёров
    let tdee = (bmr * userData.activity) + Math.round(workoutBurn * 0.35);
    if (goal === 'loss') tdee *= 0.85;
    if (goal === 'gain') tdee *= 1.15;

    const totalCalories = Math.round(tdee);
    const proteinMult = goal === 'gain' ? 2.1 : (goal === 'loss' ? 2.2 : 1.9);
    const proteinGrams = Math.round(userData.weight * proteinMult);
    const fatGrams = Math.round(userData.weight * 1.0);
    const caloriesFromProteinFat = (proteinGrams * 4) + (fatGrams * 9);
    const carbsGrams = Math.max(50, Math.round((totalCalories - caloriesFromProteinFat) / 4));

    // 4. ИМТ и вода
    const heightM = userData.height / 100;
    const bmi = (userData.weight / (heightM * heightM)).toFixed(1);
    let bmiText = 'Нормальный вес';
    if (bmi < 18.5) bmiText = 'Дефицит массы';
    else if (bmi >= 25 && bmi < 30) bmiText = 'Избыточный вес / Масса';
    else if (bmi >= 30) bmiText = 'Высокий ИМТ';

    const waterLiters = ((userData.weight * 0.033) + (workoutBurn / 700)).toFixed(1);

    $('bmr-sub').textContent = 'Базовый обмен: ' + bmr + ' ккал';
    $('workout-burn-value').textContent = workoutBurn;
    $('workout-duration-sub').textContent = 'Длительность: ~' + estDurationMin + ' мин (' + sampleWorkout.length + ' упр.)';
    $('bmi-value').textContent = bmi;
    $('bmi-status-sub').textContent = bmiText;
    $('water-value').textContent = waterLiters;

    // Обновляем баннер расчёта тренировки
    $('calc-mode-label').textContent = place === 'gym'
        ? ('Зал (' + activeMachines.length + ' из ' + machinesDB.length + ' трен.)')
        : ('Дома (' + selectedEquipment.length + ' вид. инв.)');
    $('calc-avail-count').textContent = activeMyExercises.length + ' упр.';
    $('calc-scheme-label').textContent = goal === 'loss' ? '3-4 × 14-18' : (goal === 'gain' ? '4 × 6-10' : '3-4 × 10-12');
    $('calc-rest-label').textContent = goal === 'loss' ? '45-60 сек' : (goal === 'gain' ? '90-120 сек' : '60-90 сек');

    // 5. Персональные рекомендации с учётом выбранных тренажёров
    if (adviceBox) {
        adviceBox.style.display = 'block';
        let machineSummary = '';
        if (place === 'gym') {
            const selectedNames = machinesDB
                .filter(function(m) { return activeMachines.includes(m.id); })
                .slice(0, 5)
                .map(function(m) { return m.name.split(' (')[0]; });
            const favActive = machinesDB.filter(function(m) { return activeMachines.includes(m.id) && likedMachines.includes(m.id); });
            machineSummary = '<br><br><strong>Влияние выбранных тренажёров (' + activeMachines.length + ' шт.):</strong> ' +
                'В расчёт включены упражнения для: <i>' + esc(selectedNames.join(', ')) + (activeMachines.length > 5 ? ' и др.' : '') + '</i>. ' +
                (favActive.length ? 'Приоритет отдан вашим ❤️ любимым тренажёрам (' + favActive.length + ' шт.). ' : '') +
                'Для каждого тренажёра ниже автоматически рассчитан стартовый рабочий вес под ваши ' + userData.weight + ' кг.';
        } else {
            const eqNames = selectedEquipment.map(function(k) { return EQUIP[k] || k; });
            machineSummary = '<br><br><strong>Влияние выбранного инвентаря:</strong> ' +
                'Программа адаптирована под: <i>' + esc(eqNames.join(', ')) + '</i>. Недоступные тренажёры исключены из расчёта.';
        }

        if (userData.targetWeight > userData.weight) {
            const diff = (userData.targetWeight - userData.weight).toFixed(1);
            const weeks = userData.targetDays / 7;
            const kgPerWeek = (diff / weeks).toFixed(2);
            let speedWarning = '';
            if (kgPerWeek > 0.5) speedWarning = ' <span style="color: #ffa726;">(Внимание: ' + kgPerWeek + ' кг/нед — высокий темп, следите за процентом жира)</span>.';
            adviceBox.innerHTML = '<strong>Анализ: Набор мышечной массы</strong>' +
                'Цель — набрать ' + diff + ' кг за ' + userData.targetDays + ' дней (темп: <b>' + kgPerWeek + ' кг/нед</b>)' + speedWarning +
                '<br>Делайте акцент на базовых движениях и прогрессии рабочих весов.' + machineSummary;
        } else if (userData.targetWeight < userData.weight) {
            const diff = (userData.weight - userData.targetWeight).toFixed(1);
            const weeks = userData.targetDays / 7;
            const kgPerWeek = (diff / weeks).toFixed(2);
            let speedWarning = '';
            if (kgPerWeek > 1.0) speedWarning = ' <span style="color: #ff5252;">(Опасно: сброс ' + kgPerWeek + ' кг/нед грозит потерей мышц!)</span>.';
            adviceBox.innerHTML = '<strong>Анализ: Снижение веса и рельеф</strong>' +
                'Предстоит сбросить ' + diff + ' кг за ' + userData.targetDays + ' дней (темп: <b>' + kgPerWeek + ' кг/нед</b>)' + speedWarning +
                '<br>Держите высокий белок (' + proteinGrams + ' г/день) и сокращайте паузы отдыха между подходами.' + machineSummary;
        } else {
            adviceBox.innerHTML = '<strong>Анализ: Рекомпозиция и поддержание формы</strong>' +
                'Оптимальный баланс калорий (' + totalCalories + ' ккал) для укрепления мускулатуры и снижения жировой прослойки при весе ' + userData.weight + ' кг.' + machineSummary;
        }
    }

    caloriesValue.textContent = totalCalories;
    uiMacros.protein.text.textContent = proteinGrams;
    uiMacros.fat.text.textContent = fatGrams;
    uiMacros.carbs.text.textContent = carbsGrams;

    const maxProtein = 250;
    const maxFat = 120;
    const maxCarbs = 500;

    setTimeout(function() {
        uiMacros.protein.bar.style.width = Math.min((proteinGrams / maxProtein) * 100, 100) + '%';
        uiMacros.fat.bar.style.width = Math.min((fatGrams / maxFat) * 100, 100) + '%';
        uiMacros.carbs.bar.style.width = Math.min((carbsGrams / maxCarbs) * 100, 100) + '%';
    }, 30);

    lastCalculatedMetrics = {
        gender: userData.gender,
        age: userData.age,
        weight: userData.weight,
        targetWeight: userData.targetWeight,
        targetDays: userData.targetDays,
        height: userData.height,
        activity: userData.activity,
        goal: goal,
        totalCalories: totalCalories,
        workoutBurn: workoutBurn
    };

    updateAccountSummaryCards();
    return true;
}

